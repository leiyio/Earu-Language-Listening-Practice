// 记号：{@sort}、{@sort.lc}。带 @，所以不会和句子里的参数（{n}、{appName} 这类，\w+）混在一起
export const NAME_TOKEN = /\{@([\w.]+)\}/g;

// 把一句话里的记号换成名字；名字表里没有的记号直接报错（写错记号在测试里就炸，不会带着 {@xx} 上线）
export function fillNames(lang, s) {
  if (typeof s !== 'string' || !s.includes('{@')) return s;
  const names = FEATURE_NAMES[lang];
  if (!names) throw new Error(`featureNames: 没有 ${lang} 的名字表`);
  return s.replace(NAME_TOKEN, (m, id) => {
    if (!Object.hasOwn(names, id)) throw new Error(`featureNames: ${lang} 的名字表里没有 ${id}`);
    return names[id];
  });
}

// 语言包文件用它包一层：export default withNames('de', { ... })
export function withNames(lang, pack) {
  const out = {};
  for (const [k, v] of Object.entries(pack)) out[k] = fillNames(lang, v);
  return out;
}
