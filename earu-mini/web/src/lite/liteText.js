// lt('gateTitle', { name: '本地视频' })
export function lt(key, vars) {
  const lang = TEXT[renderLang()] ? renderLang() : 'en';
  let s = TEXT[lang][key] ?? TEXT.en[key] ?? key;
  s = fillNames(lang, s);
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

